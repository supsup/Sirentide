package com.sirentide;

import java.nio.file.Path;

/// WHERE GENERATED EXAMPLE ARTIFACTS GO, answered in one place (sirentide room 1197).
///
/// The tests that render the gallery PNGs, GALLERY.md, the showcase page and the per-type pages
/// used to write straight into the TRACKED examples tree on every run that found a browser. The
/// gallery PNG bytes depend on the host's Chromium, so an ordinary suite run on a Mac rewrote
/// tracked files, and the land rail (which runs the suite and then refuses a dirty tree) refused
/// every land.
///
/// THE RULE THIS CLASS HOLDS: a default run writes under the build directory, in a tree that
/// mirrors the tracked one, and the tracked tree is written ONLY under an explicit switch.
///
///     default                       build/generated-examples/...      (ignored by git)
///     -Dsirentide.regenerate=true   the tracked examples tree         (and a banner)
///
/// This is the only test source that spells the tracked directory. GeneratedExamplesTest carries a
/// census for that, and states what a text census can and cannot see. The behavioural half is the
/// examples write audit on the test task in build.gradle.kts, which compares the tracked tree
/// before and after the test JVM and does not care how a writer spelled its path.
final class GeneratedExamples {

    /// THE switch. Forwarded to the test JVM by build.gradle.kts; GeneratedExamplesTest pins that.
    static final String SWITCH = "sirentide.regenerate";

    /// The older, NARROWER showcase switch, still honoured for the HTML pages only.
    ///
    /// It is kept for a measured reason rather than out of caution: every tracked generated page
    /// carries this flag in its own "Regen:" comment, and ShowcaseGenTest byte-compares the
    /// generated showcase with the tracked one on every default run. Renaming the flag inside the
    /// page template would change the generated bytes and so require regenerating the tracked
    /// pages in the same change. Until that is done deliberately, the command the tracked pages
    /// advertise must keep working. It never redirects the host-dependent gallery PNGs.
    static final String LEGACY_SHOWCASE_SWITCH = "sirentide.updateShowcase";

    private static final Path TRACKED = Path.of("examples");
    private static final Path BUILD = Path.of("build", "generated-examples");

    private GeneratedExamples() {
    }

    /// True only under the explicit switch. Read on every call, never cached in a static, so the
    /// property test can exercise both arms in one JVM.
    static boolean regenerating() {
        return Boolean.getBoolean(SWITCH);
    }

    /// The HTML pages regenerate under the switch or under their older, narrower flag.
    static boolean regeneratingShowcase() {
        return regenerating() || Boolean.getBoolean(LEGACY_SHOWCASE_SWITCH);
    }

    /// The single decision. Private, so no caller can ask for the tracked tree by passing `true`.
    private static Path outputRoot(boolean intoTrackedTree) {
        return (intoTrackedTree ? TRACKED : BUILD).toAbsolutePath();
    }

    /// Where the gallery PNGs and GALLERY.md are WRITTEN by this run.
    static Path galleryOutputDir() {
        return outputRoot(regenerating()).resolve("gallery");
    }

    /// Where the showcase page and the per-type pages are WRITTEN by this run.
    static Path showcaseOutputDir() {
        return outputRoot(regeneratingShowcase());
    }

    /// A path inside the TRACKED tree, for READING a committed reference. Comparisons against the
    /// committed HTML and Markdown go through here in every mode, so a default run still compares
    /// generated content with what is committed and never with its own output.
    static Path tracked(String first, String... more) {
        return TRACKED.resolve(Path.of(first, more)).toAbsolutePath();
    }

    /// The default-mode root, exposed so a failure message can say where the generated copy is.
    static Path buildRoot() {
        return BUILD.toAbsolutePath();
    }

    /// THE LOUD LINE. A run that rewrote tracked references must not look like an ordinary green.
    ///
    /// `browser` is whatever identity the caller could establish. A class that launched a browser
    /// passes its user agent; a class that renders no pixels says so.
    static String banner(String testClass, String wrote, String browser) {
        return "SIRENTIDE EXAMPLES REGEN: " + testClass + " is writing " + wrote
            + " into the TRACKED examples tree. host=" + System.getProperty("os.name") + " "
            + System.getProperty("os.version") + " " + System.getProperty("os.arch")
            + "; browser=" + browser + "; BREWSHOT_CHROME=" + envOrUnset("BREWSHOT_CHROME")
            + ". The committed gallery PNGs are the LINUX render (docs/gallery-linux-check.md);"
            + " commit regenerated PNGs only from that reference host.";
    }

    /// Printing is its own act, separate from composing, so each can be tested.
    static void announce(String testClass, String wrote, String browser) {
        System.err.println(banner(testClass, wrote, browser));
    }

    private static String envOrUnset(String name) {
        String value = System.getenv(name);
        return value == null || value.isBlank() ? "(unset, BrewShot discovers the browser)" : value;
    }
}
